/** Single-user panel: the only remaining gate hides the experimental lab. */
export function useNavItems() {
  const configStore = useConfigStore()
  return computed(() =>
    NAV_ITEMS.filter((item) => {
      if (item.experimental && !configStore.experimentalFeatures) return false
      return true
    }),
  )
}

/** `/dashboard` is exact so it does not swallow every other route. */
export function isActivePath(currentPath: string, itemPath: string) {
  if (itemPath === '/dashboard') return currentPath === '/dashboard'
  return currentPath === itemPath || currentPath.startsWith(itemPath + '/')
}
